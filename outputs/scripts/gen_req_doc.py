def set_east_asia(run):
    run.font.name = 'Calibri'
    rpr = run._element.get_or_add_rPr()
    rpr.get_or_add_rFonts().set(qn('w:eastAsia'), '微软雅黑')

def p(text, bold=False, size=10.5, color=None, align=None, style_name=None, space_after=4):
    para = DOC.add_paragraph(style=style_name) if style_name else DOC.add_paragraph()
    run = para.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    set_east_asia(run)
    para.paragraph_format.space_after = Pt(space_after)
    if align == 'center':
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return para

def h(level, text):
    para = DOC.add_heading(text, level=level)
    for run in para.runs:
        set_east_asia(run)
    return para

def bullets(items, style_name='List Bullet'):
    for it in items:
        para = DOC.add_paragraph(style=style_name)
        run = para.add_run(it)
        run.font.size = Pt(10.5)
        set_east_asia(run)
        para.paragraph_format.space_after = Pt(2)

def table(headers, rows, widths=None):
    t = DOC.add_table(rows=1, cols=len(headers))
    t.style = 'Light Grid Accent 1'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ''
        run = hdr[i].paragraphs[0].add_run(htxt)
        run.bold = True
        run.font.size = Pt(10)
        set_east_asia(run)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            run = cells[i].paragraphs[0].add_run(str(val))
            run.font.size = Pt(9.5)
            set_east_asia(run)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    DOC.add_paragraph()
    return t

